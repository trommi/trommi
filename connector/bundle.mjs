#!/usr/bin/env node
// bundle.mjs: the connector as ONE self-contained file, for machines without a checkout of this repository.
//
//   node connector/bundle.mjs           write app/web/public/gen/connector.mjs and connector.mjs.sha256
//   node connector/bundle.mjs --check   fail when the committed bundle differs from what the sources make (CI)
//
// connector/channel.mjs + core/ + @modelcontextprotocol/sdk + zod, bundled by esbuild (a pinned devDependency) into
// one ES module. The connect script (app/web/public/connect.sh, served at https://app.trommi.com/connect) downloads it
// to ~/.local/share/trommi/connector/channel.mjs and checks it against connector.mjs.sha256.
//
// Why committed and not built by Cloudflare: Cloudflare's build runs in app/web, which has no package.json and no
// node_modules (the MCP SDK and esbuild live at the repository root), and the app's build step is dependency-free on
// purpose. So the bundle is generated here, committed, and the Test workflow runs --check: a change to the connector
// or the core without a new bundle fails CI.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'
import { marketplaceFiles } from './plugin.mjs'

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(REPO, 'app/web/public/gen/connector.mjs')
// The Claude Code plugin and its marketplace (connector/plugin.mjs), served at https://app.trommi.com/plugins/.
const PLUGINS = path.join(REPO, 'app/web/public/gen/plugins')
const pluginsOnDisk = () => { try { return Object.fromEntries(fs.readdirSync(PLUGINS).sort().map(f => [f, fs.readFileSync(path.join(PLUGINS, f))])) } catch { return {} } }

export async function bundle() {
  const r = await esbuild.build({
    absWorkingDir: REPO,
    entryPoints: ['connector/channel.mjs'],
    bundle: true, platform: 'node', format: 'esm', target: 'node22',
    write: false, legalComments: 'none', logLevel: 'error', minify: true, keepNames: true,
    // reload.mjs: in the bundle there are no sibling files to hot-reload; any change of the file needs a restart.
    define: { __TROMMI_BUNDLE__: 'true' },
    // CommonJS dependencies of the SDK call require() for Node built-ins; an ES module has none of its own.
    banner: { js: `// Trommi connector, one file. Generated by connector/bundle.mjs from connector/ and core/; do not edit.\nimport { createRequire as __trommiRequire } from 'node:module'; const require = __trommiRequire(import.meta.url);` },
  })
  return r.outputFiles[0].text
}

const sha = text => crypto.createHash('sha256').update(text).digest('hex')

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = await bundle()
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (have !== text) { console.error('connector bundle is stale: run node connector/bundle.mjs and commit app/web/public/gen/connector.mjs'); process.exit(1) }
    const want = marketplaceFiles(text), disk = pluginsOnDisk()
    if (Object.keys(want).sort().join() !== Object.keys(disk).join() || Object.entries(want).some(([f, b]) => !b.equals(disk[f]))) { console.error('plugin marketplace is stale: run node connector/bundle.mjs and commit app/web/public/gen/plugins/'); process.exit(1) }
    console.log(`connector bundle current (${(text.length / 1024).toFixed(0)} KiB, sha256 ${sha(text).slice(0, 12)})`)
  } else {
    fs.writeFileSync(OUT, text)
    fs.writeFileSync(`${OUT}.sha256`, `${sha(text)}\n`)
    fs.rmSync(PLUGINS, { recursive: true, force: true })
    fs.mkdirSync(PLUGINS, { recursive: true })
    for (const [f, b] of Object.entries(marketplaceFiles(text))) fs.writeFileSync(path.join(PLUGINS, f), b)
    console.log(`wrote ${path.relative(REPO, OUT)} (${(text.length / 1024).toFixed(0)} KiB, sha256 ${sha(text).slice(0, 12)})`)
  }
}
